-- Apply in staging first, then production. This is an additive migration; no user data is deleted.
begin;
create extension if not exists pgcrypto;

create table if not exists public.subscriptions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  plan_type text default 'free', status text default 'free', created_at timestamptz default now()
);
alter table public.subscriptions add column if not exists provider text;
alter table public.subscriptions add column if not exists provider_customer_id text;
alter table public.subscriptions add column if not exists provider_subscription_id text;
alter table public.subscriptions add column if not exists current_period_end timestamptz;
alter table public.subscriptions add column if not exists cancel_at_period_end boolean not null default false;
alter table public.subscriptions add column if not exists updated_at timestamptz not null default now();
alter table public.subscriptions add column if not exists provider_event_time bigint not null default 0;
-- Keep one row per user before enforcing the application invariant. Review duplicates in staging first.
delete from public.subscriptions a using public.subscriptions b
where a.user_id=b.user_id and a.ctid<b.ctid;
create unique index if not exists subscriptions_one_per_user on public.subscriptions(user_id);
do $$ declare c record; begin
  for c in select conname from pg_constraint where conrelid='public.subscriptions'::regclass and contype='c'
    and pg_get_constraintdef(oid) ~ '(plan_type|status)' loop
    execute format('alter table public.subscriptions drop constraint %I',c.conname);
  end loop;
end $$;
update public.subscriptions set plan_type=case when plan_type in ('master','warrior','pro') then 'pro' else 'free' end;
update public.subscriptions set status=case when status in ('active','trialing','past_due','canceled','free','expired') then status else 'expired' end;
alter table public.subscriptions add constraint subscriptions_launch_plan check(plan_type in ('free','pro'));

create table if not exists public.payment_events (
  id bigint generated by default as identity primary key,
  provider text not null, provider_event_id text not null unique, event_type text not null,
  payload jsonb not null, processed_at timestamptz, created_at timestamptz not null default now()
);
create table if not exists public.checkout_sessions (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id),
  provider_id text not null unique, mode text not null check(mode in ('order','subscription')),
  billing_cycle text not null check(billing_cycle in ('monthly','yearly')),
  amount integer not null, currency text not null default 'INR', created_at timestamptz not null default now()
);
create table if not exists public.payment_receipts (
  payment_id text primary key, user_id uuid not null references auth.users(id), amount integer not null,
  currency text not null, period_end timestamptz, email_sent_at timestamptz, created_at timestamptz not null default now()
);
create table if not exists public.rescue_sessions (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
  client_session_id text not null, friction_type text not null, task_text text,
  initial_action jsonb not null, final_action jsonb, adaptations jsonb not null default '[]',
  status text not null check(status in ('started','completed','stopped')),
  started_at timestamptz not null default now(), completed_at timestamptz, created_at timestamptz not null default now(),
  unique(user_id,client_session_id)
);
create table if not exists public.rescue_events (
  id bigint generated by default as identity primary key, event_name text not null, session_id text,
  properties jsonb not null default '{}', created_at timestamptz not null default now()
);
create table if not exists public.email_requests (
  bucket text primary key, count integer not null, reset_at timestamptz not null
);
create table if not exists public.ai_allowance (
  user_id uuid primary key references auth.users(id) on delete cascade,
  day date not null default current_date, month date not null default date_trunc('month',now()),
  daily_used integer not null default 0, monthly_used integer not null default 0
);
create table if not exists public.ai_request_usage (
  id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id),
  prompt_tokens integer not null, completion_tokens integer not null, estimated_cost numeric,
  created_at timestamptz not null default now()
);
create table if not exists public.rescue_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  default_friction text not null default 'not-sure', reminder_at timestamptz,
  reminder_sent_at timestamptz, updated_at timestamptz not null default now()
);
create table if not exists public.product_feedback (
  id uuid primary key default gen_random_uuid(), helpful boolean not null,
  comment text, created_at timestamptz not null default now()
);

-- Remove historical write grants/policies from authoritative billing/usage tables.
do $$ declare t text; p record; begin
  foreach t in array array['subscriptions','payment_events','checkout_sessions','payment_receipts','rescue_sessions','rescue_events','email_requests','ai_allowance','ai_request_usage','rescue_preferences','product_feedback'] loop
    execute format('alter table public.%I enable row level security',t);
    for p in select policyname from pg_policies where schemaname='public' and tablename=t loop
      execute format('drop policy %I on public.%I',p.policyname,t);
    end loop;
    execute format('revoke all on public.%I from anon, authenticated',t);
    execute format('grant all on public.%I to service_role',t);
  end loop;
end $$;
grant select on public.subscriptions to authenticated;
create policy subscriptions_read_own on public.subscriptions for select to authenticated using(auth.uid()=user_id);
grant select, delete on public.rescue_sessions to authenticated;
create policy rescue_read_own on public.rescue_sessions for select to authenticated using(auth.uid()=user_id);
create policy rescue_delete_own on public.rescue_sessions for delete to authenticated using(auth.uid()=user_id);
grant select, insert, update on public.rescue_preferences to authenticated;
create policy preferences_own on public.rescue_preferences for all to authenticated using(auth.uid()=user_id) with check(auth.uid()=user_id);
create index if not exists rescue_events_session on public.rescue_events(session_id,created_at);

create or replace function public.read_ai_allowance(user_uuid uuid)
returns table(allowed boolean, used integer, usage_limit integer, plan_type text, monthly_used integer, monthly_limit integer)
language plpgsql security definer set search_path=public as $$
declare p text; d integer; m integer; a public.ai_allowance; today date := (now() at time zone 'Asia/Kolkata')::date;
begin
  select case when s.plan_type='pro' and s.status in ('active','trialing') and s.current_period_end>now() then 'pro' else 'free' end into p
  from subscriptions s where s.user_id=user_uuid;
  p:=coalesce(p,'free'); d:=case when p='pro' then 20 else 3 end; m:=case when p='pro' then 300 else 60 end;
  select * into a from ai_allowance where user_id=user_uuid;
  return query select coalesce(case when a.day=today then a.daily_used else 0 end,0)<d
      and coalesce(case when a.month=date_trunc('month',today)::date then a.monthly_used else 0 end,0)<m,
    coalesce(case when a.day=today then a.daily_used else 0 end,0),d,p,
    coalesce(case when a.month=date_trunc('month',today)::date then a.monthly_used else 0 end,0),m;
end $$;
create or replace function public.consume_ai_breakdown(user_uuid uuid)
returns table(allowed boolean, used integer, usage_limit integer, plan_type text, monthly_used integer, monthly_limit integer)
language plpgsql security definer set search_path=public as $$
declare r record; today date := (now() at time zone 'Asia/Kolkata')::date;
begin
  insert into ai_allowance(user_id) values(user_uuid) on conflict do nothing;
  perform 1 from ai_allowance where user_id=user_uuid for update;
  select * into r from read_ai_allowance(user_uuid);
  if r.allowed then
    update ai_allowance set daily_used=r.used+1, monthly_used=r.monthly_used+1, day=today,
      month=date_trunc('month',today)::date where user_id=user_uuid;
    r.used:=r.used+1; r.monthly_used:=r.monthly_used+1;
  end if;
  return query select r.allowed,r.used,r.usage_limit,r.plan_type,r.monthly_used,r.monthly_limit;
end $$;

-- Single transaction: deduplicate event and payment, validate server checkout, apply only newer subscription state.
create or replace function public.apply_razorpay_event(event_id text, event_body jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare e text:=event_body->>'event'; pay jsonb:=event_body#>'{payload,payment,entity}';
  sub jsonb:=event_body#>'{payload,subscription,entity}'; checkout public.checkout_sessions;
  event_time bigint:=coalesce((event_body->>'created_at')::bigint,0); period_end timestamptz; new_status text;
  receipt_new boolean:=false;
begin
  perform pg_advisory_xact_lock(hashtext(event_id));
  if exists(select 1 from payment_events where provider_event_id=event_id and processed_at is not null) then return '{"duplicate":true}'; end if;
  insert into payment_events(provider,provider_event_id,event_type,payload) values('razorpay',event_id,e,event_body) on conflict do nothing;
  select * into checkout from checkout_sessions where provider_id=coalesce(pay->>'order_id',sub->>'id')
    or provider_id=coalesce(pay->>'subscription_id',sub->>'id') limit 1;
  if checkout.id is null then raise exception 'Unknown checkout reference'; end if;
  if e in ('payment.captured','subscription.activated','subscription.charged') then
    if e in ('payment.captured','subscription.charged') and (pay->>'status'<>'captured' or (pay->>'amount')::integer<>checkout.amount or pay->>'currency'<>checkout.currency) then
      raise exception 'Payment does not match checkout';
    end if;
    period_end:=case when checkout.mode='subscription' then to_timestamp((sub->>'current_end')::bigint)
      else to_timestamp(event_time) + case when checkout.billing_cycle='monthly' then interval '1 month' else interval '1 year' end end;
    if period_end is null then raise exception 'Missing paid period'; end if;
    insert into payment_receipts(payment_id,user_id,amount,currency,period_end)
      values(pay->>'id',checkout.user_id,checkout.amount,checkout.currency,period_end) on conflict do nothing;
    receipt_new:=found;
    new_status:='active';
  elsif e in ('payment.failed','subscription.halted','subscription.pending') then new_status:='past_due';
  elsif e in ('subscription.cancelled','subscription.completed') then
    new_status:='canceled';
    period_end:=to_timestamp((sub->>'current_end')::bigint);
  else
    update payment_events set processed_at=now() where provider_event_id=event_id;
    return '{"ignored":true}';
  end if;
  if receipt_new or e not in ('payment.captured','subscription.activated','subscription.charged') then
    insert into subscriptions(user_id,provider,provider_subscription_id,plan_type,status,current_period_end,cancel_at_period_end,provider_event_time)
      values(checkout.user_id,'razorpay',case when checkout.mode='subscription' then checkout.provider_id end,'pro',new_status,period_end,new_status='canceled',event_time)
    on conflict(user_id) do update set provider='razorpay',provider_subscription_id=excluded.provider_subscription_id,
      plan_type='pro',status=excluded.status,current_period_end=coalesce(excluded.current_period_end,subscriptions.current_period_end),
      cancel_at_period_end=excluded.cancel_at_period_end,provider_event_time=excluded.provider_event_time,updated_at=now()
    where subscriptions.provider_event_time<=excluded.provider_event_time;
  end if;
  update payment_events set processed_at=now() where provider_event_id=event_id;
  return jsonb_build_object('user_id',checkout.user_id,'payment_id',pay->>'id','receipt_new',receipt_new,'billing_cycle',checkout.billing_cycle);
end $$;

create or replace function public.consume_email_request(bucket_key text, max_requests integer, window_seconds integer)
returns boolean language plpgsql security definer set search_path=public as $$
declare r public.email_requests;
begin
  insert into email_requests values(bucket_key,0,now()+make_interval(secs=>window_seconds)) on conflict do nothing;
  select * into r from email_requests where bucket=bucket_key for update;
  if r.reset_at<=now() then r.count:=0; r.reset_at:=now()+make_interval(secs=>window_seconds); end if;
  if r.count>=max_requests then return false; end if;
  update email_requests set count=r.count+1,reset_at=r.reset_at where bucket=bucket_key;
  return true;
end $$;

revoke all on function public.read_ai_allowance(uuid), public.consume_ai_breakdown(uuid), public.apply_razorpay_event(text,jsonb), public.consume_email_request(text,integer,integer) from public;
grant execute on function public.read_ai_allowance(uuid), public.consume_ai_breakdown(uuid), public.apply_razorpay_event(text,jsonb), public.consume_email_request(text,integer,integer) to service_role;
commit;
